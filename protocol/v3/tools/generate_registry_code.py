#!/usr/bin/env python3
from __future__ import annotations
import argparse,json,pathlib,sys
ROOT=pathlib.Path(__file__).resolve().parents[1]

def load():
    records=json.loads((ROOT/'schemas/record-registry.json').read_text())['records']
    algs=json.loads((ROOT/'schemas/algorithm-registry.json').read_text())
    suites=json.loads((ROOT/'registries/security-suites.json').read_text())['suites']
    return sorted((int(k),v) for k,v in records.items()),algs,suites

def render_python(record_items,algs,suites):
    suite_by_name={x['name']:int(x['id']) for x in suites}
    suite_status={x['name']:x['status'] for x in suites}
    fec_by_name={x['name']:int(x['id']) for x in algs['fec']}
    fec_status={x['name']:x['status'] for x in algs['fec']}
    return ('# GENERATED by tools/generate_registry_code.py. DO NOT EDIT.\n'
            f'RECORD_TYPES = {dict(record_items)!r}\n'
            f'SECURITY_SUITE_IDS = {suite_by_name!r}\n'
            f'SECURITY_SUITE_STATUS = {suite_status!r}\n'
            f'FEC_ALGORITHM_IDS = {fec_by_name!r}\n'
            f'FEC_ALGORITHM_STATUS = {fec_status!r}\n')

def rs(s:str)->str:
    return json.dumps(s)

def render_rust(record_items,algs,suites):
    suite_rows=sorted((x['name'],int(x['id']),x['status']) for x in suites)
    fec_rows=sorted((x['name'],int(x['id']),x['status']) for x in algs['fec'])
    out=['// GENERATED by tools/generate_registry_code.py. DO NOT EDIT.']
    out.append('pub const KNOWN_TYPES:&[u16]=&['+','.join(str(k) for k,_ in record_items)+'];')
    out.append('pub const RECORD_TYPES:&[(u16,&str)]=&['+','.join(f'({k},{rs(v)})' for k,v in record_items)+'];')
    out.append('pub const SECURITY_SUITES:&[(&str,u16,&str)]=&['+','.join(f'({rs(n)},{i},{rs(st)})' for n,i,st in suite_rows)+'];')
    out.append('pub const FEC_ALGORITHMS:&[(&str,u8,&str)]=&['+','.join(f'({rs(n)},{i},{rs(st)})' for n,i,st in fec_rows)+'];')
    dev=next(i for n,i,_ in suite_rows if n=='development-hmac')
    out.append(f'pub const DEVELOPMENT_HMAC_SUITE_ID:u16={dev};')
    return '\n'.join(out)+'\n'

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
    rec,algs,suites=load();outputs={
      ROOT/'src/dbp3/generated_registry.py':render_python(rec,algs,suites),
      ROOT/'rust/dbp3-ref/src/generated_registry.rs':render_rust(rec,algs,suites),
    }
    stale=[]
    for p,text in outputs.items():
        if a.check:
            if not p.exists() or p.read_text()!=text: stale.append(str(p.relative_to(ROOT)))
        else:p.write_text(text)
    if stale: raise SystemExit('STALE GENERATED REGISTRY: '+', '.join(stale)+'; run tools/generate_registry_code.py')
    if a.check: print(f'generated registry freshness verified: {len(rec)} record ids, {len(suites)} suites, {len(algs["fec"])} FEC algorithms')
    else: print(f'generated {len(rec)} record ids, {len(suites)} suites, {len(algs["fec"])} FEC algorithms')
if __name__=='__main__':main()
